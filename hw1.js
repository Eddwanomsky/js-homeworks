// 1
// Кроки:
// 1) Спочатку виконується додавання: 'number' + 3. Через те, що один з операндів - string, число 3 стає '3'. Виходить 'number3'
// 2) 'number3' + 3. Знову додавання зі string, число 3 стає '3'
// 3) Результат: 'number33'
console.log('number' + 3 + 3);

// 2
// Кроки:
// 1) Операція додавання з числом приводить null до числового типу.
// 2) Number(null) перетворюється на 0.
// 3) Обчислення: 0+3=3
console.log(null + 3);

// 3
// Кроки:
// 1) Логічне I обчислює вирази зліва направо та повертає перше хибне значення, або останнє істинне, якщо всі істинні.
// 2) Число 5 є істинне
// 3) Оскільки перший операнд істиний, оператор повертає qwerty
console.log(5 && "qwerty");

// 4
// Кроки:
// 1) Подвійні плюси мають найвищий пріоритет і перетворюють числа 40 і 2 на текст
// 2) Додаємо числа 40 + 2 = 42
// 3) Додаємо 42 + "hillel". Число 42 приводиться до тексту '42'
// 4) Результат: "42hillel"
console.log(+'40' + +'2' + "hillel");

// 5
// Кроки:
// 1) Оператор віднімання приводить string '10' до числа 10
// 2) Виконується віднімання: 10 - 5 = 5
// 3) Виконується суворе порівняння: 5 === 6
// 4) Оскільки числа не рівні, отримуємо false
console.log('10' - 5 === 6);

// 6
// Кроки:
// 1) Математичний плюс приводить булеві значення до чисел
// 2) Number(true) стає 1, а Number(false) стає 0
// 3) Обчислення: 1 + 0 = 1
console.log(true + false);

// 7
// Кроки:
// 1) Оператор мінус намагається привести string '4px' до числа
// 2) Оскільки string містить букви 'px', Number('4px') повертає NaN (Not a Number)
// 3) Будь-яка математична операція з NaN повертає NaN
console.log('4px' - 3);

// 8
// Кроки:
// 1) Оператор віднімання приводить string '4' до числа 4
// 2) Виконується віднімання: 4 - 3 = 1
console.log('4' - 3);

// 9
// Кроки:
// 1) Піднесення до степеня `**` має вищий пріоритет, ніж додавання: 3 ** 0 дорівнює 1
// 2) Оскільки перший операнд — string, число 1 перетворюється на string '1'
// 4) Результат: '6' + '1' = "61".
console.log('6' + 3 ** 0);

// 10
// Кроки:
// 1) Оператор ділення приводить string '6' до числа 6
// 2) Виконується ділення: 12 / 6 = 2
console.log(12 / '6');

// 11
// Кроки:
// 1) Спочатку виконується вираз у дужках: (5 === 6), що повертає булеве значення false
// 2) Далі виконується додавання зі string: '10' + false
// 3) Булеве значення false приводиться до string "false"
// 4) Результат: '10' + 'false' = "10false"
console.log('10' + (5 === 6));

// 12
// Кроки:
// 1) Оператор нестрогої рівності `==`: `null` дорівнює лише `null` або `undefined` за нестрогого порівняння
// 2) Оскільки порожня '' не є null або undefined, результат — false
console.log(null == '');

// 13
// Кроки:
// 1) Спочатку обчислюється вираз у дужках: 9 / 3 = 3
// 2) Виконується піднесення до степеня: 3 ** 3
// 3) Обчислення: 3 * 3 * 3 = 27
console.log(3 ** (9 / 3));

// 14
// Кроки:
// 1) Подвійне заперечення `!!` приводить значення до булевого типу.
// 2) Непорожні стрічки 'false' та 'true' є істинними значеннями (будь-яка не порожня стрічка є істиною).
// 3) !!'false' дає true, і !!'true' також дає true.
// 4) Виконується порівняння: true == true, що дає true.
console.log(!!'false' == !!'true');

// 15
// Кроки:
// 1) Оператор `&&` має вищий пріоритет за `||`, тому спочатку обчислюється: '0' && 
// 2) String '0' є не порожньою,тобто істина. Логічне І повертає останній істинний операнд, тобто 1
// 3) Залишається вираз: 0 || 1
// 4) Логічне АБО (`||`) повертає перше істинне значення. 0 — це хибне, тому повертається 1
console.log(0 || '0' && 1);

// 16
// Кроки:
// 1) Унарний плюс `+null` приводить null до числа 0
// 2) Вираз у дужках: (0 == false). При порівнянні `false` приводиться до 0. 0 == 0 повертає true
// 3) Порівняння: true < 1
// 4) Для порівняння `<` булеве значення `true` приводиться до числа 1
// 5) Отримуємо: 1 < 1, що є неправдою, тому результат false
console.log((+null == false) < 1);

// 17
// Кроки:
// 1) Оператор `&&` виконується першим через вищий пріоритет: false && true
// 2) Оскільки перший операнд хибний, `&&` одразу повертає хибне значення
// 3) Залишається вираз: false || true
// 4) Оператор `||` повертає перше істинне значення, тобто true
console.log(false && true || true);

// 18
// Кроки:
// 1) Спочатку обчислюється вираз у дужках: (false || true), що повертає true
// 2) Залишається вираз: false && true
// 3) Оператор `&&` потребує, щоб обидва операнди були істинними, тому повертає false
console.log(false && (false || true));

// 19
// Кроки:
// 1) Спочатку обчислюється піднесення до степеня: 1 ** 5 = 1
// 2) Паралельно обчислюється вираз у дужках: `+null` це 0, (0 == false) це true
// 3) Вираз підставляється: true < 1
// 4) `true` приводиться до числа 1
// 5) Порівняння 1 < 1 дає false
console.log((+null == false) < 1 ** 5);